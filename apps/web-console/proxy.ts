import { NextResponse, type NextRequest } from "next/server";

import { SESSION_COOKIE, parseSession } from "@/lib/session";
import { isStaticRun } from "@/lib/static-replay/run-id";

/**
 * 🔴 파일 이름이 `proxy.ts`인 이유: Next 16이 `middleware` 파일 규약을 deprecate 했다
 *    (빌드가 경고로 알려 준다). 새로 세우는 파일을 이미 낡은 규약으로 두지 않는다.
 *
 * 세션 «가드» — wireframes §6.
 *
 *   「모든 라우트는 세션 쿠키 없이 진입 시 `/`로 보내 세션을 먼저 만든다(격리 보장).」
 *
 * 🔴 규칙을 «한 곳»에 둔다. 페이지마다 가드를 넣으면 새 라우트가 생길 때 빠뜨리고,
 *    빠뜨린 라우트는 세션 없이 열리는 «구멍»이 된다 — 화면 목록이 늘어날수록 확실해진다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 **이 파일은 세션을 «만들지 않는다»**(Q-39 ⓒ · 이 티켓이 옮긴 층).
 *
 * 있었던 일: 입장 발급이 여기, 즉 «무세션 `/` 로의 서버 홉»에 있었다. 그런데 그 홉은
 * 방문자만 밟는 자리가 아니다 — 셸 `<Link>` 의 프리페치가 `/overview` 를 긁으면 가드가
 * 307 로 `/` 를 돌려주고, 프리페치가 그 307 을 따라가면서 **아무도 «입장»하지 않았는데
 * 세션이 발급됐다.** 딥링크(`/evidence/{id}`)로 「열람만」 들어온 방문자에게 세션이
 * 생기고, 그 `fkt_sid` 는 ai-api 에서 «진짜로 선다» = 계약 v0.1.6 「열람만」 위반.
 *
 * 🔴 **실측(BEFORE · 이 lane 기점 9949a68 · Next 16.3.3 `next start` · 브라우저 축)**:
 *    딥링크 진입 → 셸 링크 7개 hover → 프리페치 «표지» 요청 **11건** → +3초에
 *    쿠키 `fkt_sid`·`fkt_session` **2개** · 응답 `Set-Cookie` **4건**(전부 `307 /`) ·
 *    ai-api 자기 로그의 세션 발급 **4건**. 두 딥링크 라우트에서 같은 값.
 *
 * 🔴 **표지로는 못 가른다**(14대 삼중 실측): 이 층에 도달하는 헤더는 7개뿐이고, 프리페치와
 *    사람의 진짜 방문을 «여기서» 가르는 재료가 없다. 그래서 표지를 갈아 끼우는 대신 층을
 *    옮겼다 — 입장은 서버 홉이 «지나가다» 하는 일이 아니라, `/` 페이지의 클라이언트
 *    마운트가 `POST /enter` 로 **명시 호출**하는 일이다(app/enter/route.ts).
 *    프리페치는 문서를 가져올 뿐 JS 를 실행하지 않으므로, 그 경로에는 부작용이 남지 않는다.
 *
 * 🔴 그러니 여기에 `createSession`·`cookies.set` 을 다시 들이지 마라. 들이는 순간
 *    「지나가기만 해도 입장」이 되살아나고, 그것은 화면에서 조용하다.
 * ─────────────────────────────────────────────────────────────────────────────
 */
/**
 * 🔴 **읽기 전용 딥링크 예외 — 계약 v0.1.6 의 «화면» 절반**(T3-3).
 *
 * 계약은 `GET /evidence/{id}` · `GET /documents/{id}` 를 「세션 없이 열람만」으로 열었고
 * (§3:244 집행 · Q-16 긴장 해소), ai-api 쪽 절반은 T3-1 이 `READ_ONLY_EXCEPTIONS` 로 세웠다.
 * 그런데 **셸이 그 앞에서 세션 없는 방문자를 `/` 로 되돌려 보내고 있었다** — API 는 열려
 * 있는데 화면이 닫혀서, 딥링크로 들어온 사람은 근거가 아니라 `/overview` 에 도착했다.
 * 그것이 Q-16 이 「§3:244는 지금도 미구현」이라 적어 둔 상태의 실체다(levi2 6대 R-1 계보).
 *
 * 🔴 **긍정형·앵커·문자집합으로 잠근다.** 이 파일의 matcher 가 부정 전방탐색 하나로
 *    `/incidents/x.svg` 를 세션 없이 열었던 자리다(V-1) — 같은 형태를 반복하지 않는다.
 *    `\b` 도 쓰지 않는다: 경계 문자가 바뀌면 조용히 다른 자리에서 끊긴다.
 * 🔴 **세그먼트 «하나»만** 문다. `/evidence/x/y` 는 예외가 아니다 — 계약이 연 것은 단건
 *    열람 2라우트이고, 그 아래로 무엇이 자라든 그것은 새 표면이다.
 * 🔴 실패 방향: 이 정규식이 «못 물면» 방문자는 예전처럼 `/` 로 가서 목적지를 잃는다 —
 *    눈에 보이는 실패다. 반대로 넓게 물면 세션 화면이 세션 없이 열려 «조용한» 구멍이 된다.
 *    좁게 틀리는 쪽을 고른다.
 * 🔴 그리고 이 목록이 스스로를 증명하지는 못한다 — 「예외에 없으니 막힌다」는 추론이다.
 *    실증은 밖에서 온다: 자기 실측 표의 «브라우저 네트워크 축»이 세션 화면(쿠키 없으면
 *    `/` 로 튄다)과 딥링크(그대로 200)를 «같은 브라우저»에서 나란히 잰다.
 */
const READ_ONLY_DEEP_LINK = /^\/(evidence|documents)\/[^/]+$/;

/**
 * 🔴 **입장 «표면» = `/` 와 이 핸들러 둘뿐**(Q-39 ⓒ · 오케 승인 조건 ⓐ).
 *
 * Next 는 같은 경로에 `page.tsx` 와 `route.ts` 를 함께 둘 수 없다. 그래서 입장 핸들러는
 * `/` 가 아닌 별도 URL 이 되고, 무세션으로 여기까지 닿아야 입장이 «실행»된다.
 *
 * 🔴 `READ_ONLY_DEEP_LINK`(계약이 연 2라우트)는 **넓히지 않았다** — 이것은 계약 표면이
 *    아니라 셸 내부의 입장 자리다(`/api` 아님 · contract-surface 무영향).
 * 🔴 위 예외와 «같은 형태»로 잠근다: 긍정형·앵커·문자집합. 부정 전방탐색이 `/incidents/x.svg`
 *    를 열었던 자리가 이 파일이다(V-1) — 같은 형태를 반복하지 않는다.
 * 🔴 여기를 지나도 «발급»은 자동이 아니다: 핸들러는 POST 전용이라 프리페치·GET 은 405 로
 *    끝나고(부작용 0), 세션을 이미 쥔 요청에는 발급 0 으로 답한다(멱등).
 */
const ENTRY_HANDLER = /^\/enter$/;

/**
 * 정적 replay 진입 (T4-2a · 오케 판정 R-1·가드레일 ②).
 *
 * 🔴 **세션을 만들어 주지 않는다.** 딥링크 2라우트와 같은 자리다 — 지나보내기만 한다.
 *    서버 세션 쿠키(`fkt_session`·`fkt_sid`)를 정적 방문자 몫으로 «위조하지 않는다»:
 *    그 이름은 서버가 발급하고 서버가 읽는 이름이라, 정적 경로가 그것을 쓰면 서버 눈에
 *    「있는 세션」인 척하게 된다. 방문자 상태는 browser storage 가 따로 든다.
 * 🔴 **통과 표지 = `?run=` 의 «값»이다.** 정규식이 아니라 **상수 일치**로 본다 — 형식으로
 *    열면 그 형식에 맞는 임의 값이 다 들어오는데, 여는 것은 그 하나뿐이어야 한다.
 * 🔴 Live 복귀 때는 이 자리가 아무 역할도 하지 않는다 — 정식 입장(`POST /enter`)이 세션을
 *    만들고, 그때부터 위 `session` 분기가 답한다(T3-1 E-1 회귀 0).
 */
const STATIC_REPLAY_SCREEN = /^\/incidents\/[^/]+$/;

export async function proxy(req: NextRequest) {
  const session = parseSession(req.cookies.get(SESSION_COOKIE)?.value);
  const path = req.nextUrl.pathname;
  const isEntry = path === "/";

  if (session) {
    // 이미 세션이 있으면 `/`는 머무는 곳이 아니라 지나가는 곳이다.
    return isEntry ? NextResponse.redirect(new URL("/overview", req.url)) : NextResponse.next();
  }

  // 🔴 세션이 없어도 딥링크 2라우트는 «그대로» 연다. 여기서 세션을 만들어 주지도 않는다 —
  //    만들어 주면 「열람만」이 아니라 조용한 입장이 되고, 화면은 세션 화면과 구별되지 않는다.
  if (READ_ONLY_DEEP_LINK.test(path)) {
    return NextResponse.next();
  }

  // 정적 replay 화면 — 세션 없이 열되 세션을 만들지 않는다(위 성문 참조).
  if (STATIC_REPLAY_SCREEN.test(path) && isStaticRun(req.nextUrl.searchParams.get("run"))) {
    return NextResponse.next();
  }

  // 🔴 **입장 자리는 그냥 지나보낸다 — 여기서 만들지 않는다.** `/` 는 입장을 «실행하는 화면»
  //    이고 `/enter` 는 그 화면이 부르는 핸들러다. 이 줄이 예전에는 `createSession` 이었고,
  //    그래서 프리페치가 대신 입장해 버렸다(위 실측 · Q-39).
  if (isEntry || ENTRY_HANDLER.test(path)) {
    return NextResponse.next();
  }

  return NextResponse.redirect(new URL("/", req.url));
}

export const config = {
  // 🔴 `/api/*`는 가드 대상이 아니다 — 계약 호출은 rewrite로 ai-api에 그대로 나간다.
  //
  // 🔴 마지막 절이 `.*\.svg`였다(V-1 · levi2 실측). 「.svg로 끝나면 정적 자산」이라는 뜻으로
  //    적었는데, 이 부정 전방탐색은 «경로 어디서든» 걸린다 — 동적 세그먼트가 `.svg`로 끝나는
  //    id를 그대로 받으므로 `/incidents/x.svg`가 세션 없이 200으로 열렸다(3라우트 실측).
  //    확장자 한 글자로 갈렸다: `.png`·`.ico`·`xsvg`는 전부 가드가 돌았다.
  //
  //    `[^/]+\.svg$`로 «최상위 세그먼트 하나»에 한정한다. public/의 파일은 URL 경로가 곧
  //    파일 경로라 최상위 파일은 세그먼트가 하나다(현 public/ = svg 5개 · 전부 평면).
  // 🔴 이 절이 기대는 전제 = public/이 평면이라는 것. 나중에 `public/img/logo.svg`처럼
  //    중첩 자산을 두면 그 자산은 가드에 걸려 `/`로 튄다 — 이미지가 «눈에 보이게» 깨진다.
  //    잊었을 때 자산이 깨지는 쪽이지, 가드에 구멍이 나는 쪽이 아니다. 실패 방향을 그렇게 둔다.
  matcher: ["/((?!api|_next/static|_next/image|favicon.ico|[^/]+\\.svg$).*)"],
};
