"""sessionId 형식 규칙 — **한 곳** (T2-3).

계약은 인증을 두지 않고 「세션 키가 격리 단위」라고만 말한다. 그래서 서버가 보는 것은 형식뿐이다.

🔴 **「형식이 맞다」는 「그 세션이 있다」가 아니다.** 이 규칙은 격리를 «주장하지 않는다» —
   세션 저장소가 실체화되는 티켓(계약 `POST /sessions`)에서 존재 확인이 붙는다.

🔴 규칙을 두 곳에 적지 않는다. compare 와 조사 실행이 같은 문자열을 서로 다르게 받아들이면,
   화면은 한쪽에서 통과한 세션 키로 다른 쪽에서 거절당한다 — 서버가 자기 자신과 어긋나는
   자리다(V-7 이 그 형태의 결함이었다: 같은 규칙이 두 곳에 살면 한쪽만 자란다).
"""

from __future__ import annotations

import re

# 영숫자·`-`·`_` 8~64자. 값의 «내용»은 보지 않는다 — 세션 키는 서버가 발급하는 것이 아니라
# 지금은 클라이언트가 들고 오는 격리 라벨이다.
SESSION_ID_RE = re.compile(r"^[A-Za-z0-9_-]{8,64}$")


def is_valid(value: str) -> bool:
    return SESSION_ID_RE.match(value) is not None
